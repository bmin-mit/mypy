"""Extract the public API surface of a built package version."""

from __future__ import annotations

from dataclasses import dataclass

from mypy.apidiff.build import BuiltVersion
from mypy.nodes import (
    Decorator,
    FuncDef,
    MypyFile,
    OverloadedFuncDef,
    ParamSpecExpr,
    SymbolNode,
    SymbolTableNode,
    TypeAlias,
    TypeInfo,
    TypeVarExpr,
    TypeVarTupleExpr,
    Var,
)
from mypy.util import is_dunder

# Class-level dunders that describe implementation details rather than API.
SKIPPED_MEMBER_DUNDERS = frozenset(
    {
        "__slots__",
        "__module__",
        "__doc__",
        "__dict__",
        "__weakref__",
        "__annotations__",
        "__match_args__",
        "__dataclass_fields__",
        "__dataclass_params__",
        "__attrs_attrs__",
        "__orig_bases__",
        "__parameters__",
        "__qualname__",
        "__abstractmethods__",
        "__protocol_attrs__",
        "__type_params__",
        "__final__",
        # Generated by dataclasses; mirrors the fields, which are compared directly
        "__replace__",
    }
)

# Kinds of public symbols
MODULE = "module"
CLASS = "class"
FUNCTION = "function"
ATTRIBUTE = "attribute"
ALIAS = "alias"
TYPEVAR = "typevar"


@dataclass
class ApiSymbol:
    """A public module-level name (or a public module)."""

    # Public dotted path, e.g. "pkg.io.read" even if read is defined in pkg._impl
    fullname: str
    kind: str
    node: SymbolNode
    # The public module the name is reachable from
    module: str
    path: str
    line: int


@dataclass
class Member:
    """A public member of a class, possibly inherited."""

    name: str
    node: SymbolNode
    # The class in the MRO that defines the member
    defining_info: TypeInfo


def is_private_module(module: str) -> bool:
    return any(part.startswith("_") for part in module.split("."))


def symbol_kind(node: SymbolNode | None) -> str | None:
    if isinstance(node, TypeInfo):
        return CLASS
    if isinstance(node, (FuncDef, OverloadedFuncDef, Decorator)):
        return FUNCTION
    if isinstance(node, Var):
        return ATTRIBUTE
    if isinstance(node, TypeAlias):
        return ALIAS
    if isinstance(node, (TypeVarExpr, ParamSpecExpr, TypeVarTupleExpr)):
        return TYPEVAR
    if isinstance(node, MypyFile):
        return MODULE
    return None


def is_public_module_name(name: str, sym: SymbolTableNode, has_all: bool) -> bool:
    """Is a module-level name part of the public API?

    mypy already marks names missing from __all__, and imports that aren't explicitly
    re-exported (with implicit_reexport disabled), as not public.
    """
    if sym.module_hidden or not sym.module_public:
        return False
    if isinstance(sym.node, MypyFile) or sym.node is None:
        # Submodules are compared as modules of their own.
        return False
    if has_all:
        return True
    return not name.startswith("_")


def is_public_member_name(name: str) -> bool:
    if "-" in name:
        # Internal names synthesized by mypy, e.g. "__mypy-replace"
        return False
    if is_dunder(name):
        return name not in SKIPPED_MEMBER_DUNDERS
    return not name.startswith("_")


def module_of(fullname: str, modules: dict[str, MypyFile]) -> str | None:
    """Find the longest prefix of fullname that is a module."""
    parts = fullname.split(".")
    for i in range(len(parts), 0, -1):
        candidate = ".".join(parts[:i])
        if candidate in modules:
            return candidate
    return None


def node_line(node: SymbolNode) -> int:
    if isinstance(node, TypeInfo):
        return node.defn.line
    if isinstance(node, Decorator):
        return node.func.line
    if isinstance(node, OverloadedFuncDef) and node.items:
        first = node.items[0]
        return first.func.line if isinstance(first, Decorator) else first.line
    return max(node.line, 1)


def node_location(
    version: BuiltVersion, node: SymbolNode, fallback_module: str, defining_module: str | None
) -> tuple[str, int]:
    module = defining_module
    if module is None:
        module = module_of(node.fullname, version.modules) if node.fullname else None
    file = version.modules.get(module or fallback_module) or version.modules.get(fallback_module)
    path = version.display_path(file.path) if file is not None else fallback_module
    if file is not None and module != fallback_module and not version_owns(version, file):
        # Defined outside the package (e.g. a re-exported stdlib name): point at the
        # module that re-exports it instead.
        reexporter = version.modules.get(fallback_module)
        if reexporter is not None:
            return version.display_path(reexporter.path), 1
    return path, node_line(node)


def version_owns(version: BuiltVersion, file: MypyFile) -> bool:
    return file.fullname in version.package_modules


def collect_module_symbols(version: BuiltVersion) -> dict[str, ApiSymbol]:
    """Collect public modules and their public names.

    Class members are not collected here; they are compared lazily per class pair.
    """
    result: dict[str, ApiSymbol] = {}
    for module in version.package_modules:
        if is_private_module(module):
            continue
        file = version.modules[module]
        result[module] = ApiSymbol(
            module, MODULE, file, module, version.display_path(file.path), 1
        )
        has_all = "__all__" in file.names
        for name, sym in file.names.items():
            if not is_public_module_name(name, sym, has_all):
                continue
            if is_dunder(name) and not has_all:
                continue
            node = sym.node
            assert node is not None
            kind = symbol_kind(node)
            if kind is None or kind == MODULE:
                continue
            path, line = node_location(version, node, module, None)
            fullname = f"{module}.{name}"
            result[fullname] = ApiSymbol(fullname, kind, node, module, path, line)
    return result


def is_object_class(info: TypeInfo) -> bool:
    return info.fullname == "builtins.object"


def class_members(info: TypeInfo) -> dict[str, Member]:
    """Public members of a class, including inherited ones, resolved in MRO order."""
    members: dict[str, Member] = {}
    for base in info.mro:
        if is_object_class(base):
            continue
        for name, sym in base.names.items():
            if name in members or sym.node is None or not is_public_member_name(name):
                continue
            if symbol_kind(sym.node) in (None, MODULE):
                continue
            members[name] = Member(name, sym.node, base)
    return members


def member_location(
    version: BuiltVersion, member: Member, fallback_module: str
) -> tuple[str, int]:
    return node_location(version, member.node, fallback_module, member.defining_info.module_name)
