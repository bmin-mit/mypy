"""Allowlists of accepted changes, in the spirit of stubtest's --allowlist.

Each non-empty line (after stripping "#" comments) is a regular expression. It matches a
change if it fully matches either the symbol's fully qualified name, or
"<fullname>:<code>" (e.g. "pkg.read:return-widened").
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from mypy.apidiff.compare import BREAKING, INFO, Change


@dataclass
class AllowlistEntry:
    pattern: str
    regex: re.Pattern[str]
    source: str
    line: int
    used: bool = False


@dataclass
class Allowlist:
    entries: list[AllowlistEntry] = field(default_factory=list)

    @classmethod
    def from_files(cls, paths: list[str]) -> Allowlist:
        allowlist = cls()
        for path in paths:
            with open(path, encoding="utf-8") as f:
                allowlist.add_lines(f.read().splitlines(), path)
        return allowlist

    def add_lines(self, lines: list[str], source: str) -> None:
        for lineno, raw in enumerate(lines, 1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            try:
                regex = re.compile(line)
            except re.error as e:
                raise ValueError(f"{source}:{lineno}: invalid regular expression: {e}") from e
            self.entries.append(AllowlistEntry(line, regex, source, lineno))

    def matches(self, change: Change) -> bool:
        keys = (change.symbol, f"{change.symbol}:{change.code}")
        matched = False
        for entry in self.entries:
            if any(entry.regex.fullmatch(key) for key in keys):
                entry.used = True
                matched = True
        return matched

    def filter(self, changes: list[Change]) -> list[Change]:
        return [c for c in changes if not self.matches(c)]

    def unused(self) -> list[AllowlistEntry]:
        return [e for e in self.entries if not e.used]


def generate_allowlist(changes: list[Change]) -> str:
    """Allowlist entries that accept every breaking change and warning in changes."""
    entries = sorted(
        {
            f"{c.symbol}:{c.code}"
            for c in changes
            if c.severity != INFO and c.code != "unused-allowlist"
        }
    )
    header = "# Generated by apidiff --generate-allowlist\n"
    breaking = sum(1 for c in changes if c.severity == BREAKING)
    header += f"# Accepts {breaking} breaking change(s)\n"
    return header + "".join(f"{e}\n" for e in entries)
